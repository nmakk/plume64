def ink(rows): return max((len(r) for r in rows),default=0)
def merge(a,b):
    out=[]
    for x,y in zip(a,b):
        n=max(len(x),len(y)); x=x.ljust(n,'.'); y=y.ljust(n,'.')
        out.append(''.join('#' if '#'==p or '#'==q else '.' for p,q in zip(x,y)))
    return out
