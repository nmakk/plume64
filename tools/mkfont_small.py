def cat(a,b): # glue two glyphs overlapping one column
    n=ink(a)
    out=[]
    for x,y in zip(a,b):
        x=x.ljust(ink(a),'.'); y=y.ljust(ink(b),'.')
        row=list(x+'.'*(ink(b)-1))
        for i,ch in enumerate(y):
            if ch=='#': row[n-1+i]='#'
        out.append(''.join(row))
    return out
